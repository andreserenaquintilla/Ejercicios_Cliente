// 1 - Declaración de variables numéricas
var entero = 1357;        // Número entero normal (sistema decimal)
var decimal = 1357;       // Mismo valor, sistema decimal (el enunciado lo pide así)
var cientifico = 135e7;   // Notación científica: 135 * 10^7
var octal = 01357;        // Notación octal (precedido de un 0)
var hexadecimal = 0x1357; // Notación hexadecimal (precedido de 0x)

// 2 - Mostrar cada valor con un alert
alert("Número entero" + entero);
alert("Número decimal" + decimal);
alert("Número científico" + cientifico);
alert("Número octal" + octal);
alert("Número hexadecimal" + hexadecimal);