// 1 - Declaración de variables
var variable1 = "Hola";
var variable2 = "7";
var variable3 = "13";
var variable4 = "Adios";

// 2 - Mostrar las diferentes cadenas con alerts
alert("Hoy es un día `genial` para programar.");        // Este alert muestra una frase con las comillas invertidas
alert(variable1 + "\n" + variable4);                    // Este alert muestra las variables numéricas con un salto de linea
alert(variable2 + variable3);                           // Este alert parece que suma los números pero en realidad los pone uno detras de otro
alert(variable1 + variable2 + variable3 + variable4);   // Este alert muestra todas las variables concatenadas en una sola cadena